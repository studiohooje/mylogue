import assert from 'node:assert/strict';
import {connect} from './qa-cdp.mjs';
const c=await connect(9238,'http://localhost:4173');
const run=expression=>c.run(expression);
const wait=async expression=>{for(let i=0;i<50;i++){if(await run(expression))return;await new Promise(r=>setTimeout(r,100))}throw Error('Timed out: '+expression)};
const click=selector=>run(`document.querySelector(${JSON.stringify(selector)}).click()`);
const fill=(selector,value)=>run(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw Error('Missing ${selector}');e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('input',{bubbles:true}));e.dispatchEvent(new Event('change',{bubbles:true}))})()`);
try{
 await c.send('Page.enable');await c.send('Runtime.enable');
 await wait('!!document.querySelector(`[data-page="food"]`)');
 await run('localStorage.clear()');await c.send('Page.reload',{ignoreCache:true});
 await wait('!!document.querySelector(`[data-page="food"]`)');
 await click('[data-page="food"]');await click('[data-modal="batch"]');
 await fill('#q-food-search','제로핵 베이글');await click('#q-food-advanced');
 await wait('!!document.querySelector(`#batch-form`)');
 await fill('[data-food-field="name"]','제로핵 베이글');
 await fill('[data-food-field="servingUnit"]','개');
 await fill('[data-food-field="servingQty"]','1');
 await fill('[data-food-field="calories"]','190');
 await fill('[data-food-field="carbs"]','22');
 await fill('[data-food-field="protein"]','12');
 await fill('[data-food-field="fat"]','5');
 await run('document.querySelector(`#batch-form`).requestSubmit()');
 await wait('JSON.parse(localStorage.getItem("mylogue.v1")||"{}").meals?.length===1');
 const afterMeal=await run('JSON.parse(localStorage.getItem("mylogue.v1"))');
 assert.equal(afterMeal.meals[0].name,'제로핵 베이글');
 assert.equal(afterMeal.foods.find(x=>x.name==='제로핵 베이글').calories,190);
 await click('[data-page="workout"]');await click('[data-modal="workout"]');
 await fill('#q-ex-search','불가리안');
 await click('[data-q-ex="exercise:불가리안 스플릿 스쿼트"]');
 assert.equal(await run('document.querySelector(`#q-set-weight`)?.value'),undefined);
 await click('#q-first-set');
 assert.equal(await run('document.querySelector(`#q-set-weight`).value'),'0');
 await fill('#q-set-weight','5');await fill('#q-set-reps','10');
 await click('#q-save-set');
 await wait('JSON.parse(localStorage.getItem("mylogue.v1")||"{}").workouts?.length===1');
 const afterSet=await run('JSON.parse(localStorage.getItem("mylogue.v1"))');
 assert.equal(afterSet.workouts[0].exercises[0].handCount,2);
 assert.equal(afterSet.workouts[0].exercises[0].weightBasis,'per-hand');
 console.log('PASS manual food preset, quick meal, Bulgarian per-hand set');
}finally{c.close()}
