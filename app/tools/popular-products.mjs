const norm = s => String(s || '').toLocaleLowerCase('ko').replace(/[\s·()\-_/.,[\]]/g, '');
// 목표 뒤에 붙어도 되는 것: 용량(120g, 1.5L, 500ml), 포장(봉지, 멀티, 번들), 'k' 등
const TAIL_OK = /^(\d+(\.\d+)?(g|kg|ml|l|mm)?|봉지|멀티|번들|\d+입|\d+개입|\d+봉|대|소|컵|캔|병|페트|pet|용기면|\d+gx\d+)*$/;

export async function pick(){
  const want = TARGETS.map(t => ({t, key: norm(t[0]), cands: []}));
  const rl = readline.createInterface({input: fs.createReadStream(SRC, 'utf8'), crlfDelay: Infinity});
  for await (const line of rl) {
    if (!line) continue;
    const i = line.indexOf('"name":"'); if (i < 0) continue;
    const nm = norm(line.slice(i + 8, line.indexOf('"', i + 8)));
    for (const w of want) {
      if (!nm.startsWith(w.key)) continue;
      const tail = nm.slice(w.key.length);
      if (!TAIL_OK.test(tail)) continue;
      const o = JSON.parse(line);
      if (!w.t[1].test(o.maker || '') && !w.t[1].test(o.distributor || '') && !w.t[1].test(o.importer || '')) continue;
      if (!o.per100 || o.per100.kcal == null) continue;
      w.cands.push({o, exact: tail === ''});
    }
  }
  return want.map(w => {
    // 이름이 딱 같은 것 → 수정일 최신 → 분석 값
    // 'median': 여러 회사가 같은 이름으로 파는 일반 상품(구운란·탕후루)은 이름이 같은 것 중 열량이 가운데인 것
    const ex = w.cands.filter(x => x.exact).sort((a, b) => a.o.per100.kcal - b.o.per100.kcal);
    const c = w.t[4] === 'median' && ex.length ? ex[Math.floor(ex.length / 2)] : w.cands.sort((a, b) => (b.exact - a.exact) || String(b.o.source?.updated || '').localeCompare(String(a.o.source?.updated || '')) || String(b.o.source?.created || '').localeCompare(String(a.o.source?.created || '')))[0];
    return {target: w.t[0], brand: w.t[2], aliases: w.t[3], generic: w.t[4] === 'median', n: w.cands.length, pick: c?.o || null};
  });
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const res = await pick();
  const miss = res.filter(r => !r.pick);
  for (const r of res) if (r.pick) { const p = r.pick, n = p.per100; console.log(`${r.target} ⇐ ${p.name} | ${p.maker} | ${p.basis} ${n.kcal}k 탄${n.carbs} 단${n.protein} 지${n.fat} | 내용량 ${p.foodSize} 1회 ${p.servingRef} | 후보 ${r.n}`); }
  console.log('찾음', res.length - miss.length, '/', res.length, '못 찾음:', miss.map(r => r.target).join(' '));
  const out = path.join(BASE, 'products_popular'); fs.mkdirSync(out, {recursive: true});
  fs.writeFileSync(path.join(out, 'popular.json'), JSON.stringify({builtAt: new Date().toISOString().slice(0, 10), source: '식약처 식품영양성분DB(통합) 가공식품 15100066', rows: res.filter(r => r.pick).map(r => ({target: r.target, brand: r.brand, aliases: r.aliases, generic: r.generic, ...r.pick}))}, null, 1));
}
