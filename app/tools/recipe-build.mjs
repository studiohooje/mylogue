const median = a => { const s = [...a].sort((x, y) => x - y); const n = s.length; return n ? (n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2) : null; };
export function resolveIngredients({raw, dish, processed}) {
  const out = {}, report = {};
  for (const [key, spec] of Object.entries(INGREDIENTS)) {
    if (spec.zero) { out[key] = Object.fromEntries(KEYS.map(k => [k, 0])); report[key] = '물(0)'; continue; }
    if (spec.dish) { const f = dish.find(x => x.name === spec.dish && !x.maker); if (f?.per100?.kcal != null) { out[key] = f.per100; report[key] = `식약처 음식 '${f.name}'`; } continue; }
    if (spec.raw) {
      const c = raw.filter(x => spec.raw.test(x.name) && x.per100?.kcal != null);
      const pick = c.find(x => /생것\)?$/.test(x.name) && !/말린/.test(x.name)) || c[0];
      if (pick) { out[key] = pick.per100; report[key] = `원재료 '${pick.name}'`; }
      continue;
    }
    if (spec.proc) {
      const c = processed.filter(x => spec.proc.test(x.name.replace(/\(.*\)$/, '').trim()) && x.per100?.kcal != null && x.basis !== 'ml' && (!spec.kcalRange || (x.per100.kcal >= spec.kcalRange[0] && x.per100.kcal <= spec.kcalRange[1])));
      if (c.length >= 3) { out[key] = Object.fromEntries(KEYS.map(k => { const v = c.map(x => x.per100[k]).filter(v => v != null && Number.isFinite(Number(v))).map(Number); return [k, v.length >= 3 ? median(v) : null]; })); report[key] = `가공식품 ${c.length}개 중앙값`; }
    }
  }
  return {values: out, report};
}
const r1 = v => v == null ? null : Math.round(v * 10) / 10;
export function computeRecipes(values) {
  const rows = [], skipped = [];
  for (const [name, cat, items, aliases] of RECIPES) {
    const used = items.filter(([, g]) => g > 0);
    const missing = used.filter(([k]) => !values[k]).map(([k]) => k);
    if (missing.length) { skipped.push({name, missing}); continue; }
    const total = used.reduce((a, [, g]) => a + g, 0);
    const sum = Object.fromEntries(KEYS.map(k => [k, used.reduce((a, [ing, g]) => a + (values[ing][k] == null ? 0 : Number(values[ing][k]) * g / 100), 0)]));
    rows.push({name: `${name}(집밥)`, cat, grams: Math.round(total), kcal: Math.round(sum.kcal), carbs: r1(sum.carbs), protein: r1(sum.protein), fat: r1(sum.fat), micro: [r1(sum.sugar), r1(sum.fiber), r1(sum.satFat), Math.round(sum.sodium)], aliases: [name, ...String(aliases || '').split(' ').filter(Boolean)], ingredients: used});
  }
  return {rows, skipped};
}

