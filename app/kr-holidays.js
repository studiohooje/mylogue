// 2026-11-28 대표님: 운동 요일 — 일요일·법정공휴일은 빨강, 토요일은 파랑.
// 한국 법정공휴일(대체공휴일 포함). 음력 명절은 해마다 날짜가 달라 표로 둔다.
// shortcut: 2026·2027년만 있음, 2027년 가을쯤 2028년을 덧붙일 것(제헌절 공휴일 재지정 등 법 개정도 그때 반영)
const H = {
 2026: ['01-01', '02-16', '02-17', '02-18', '03-01', '03-02', '05-05', '05-24', '05-25', '06-03', '06-06', '08-15', '08-17', '09-24', '09-25', '09-26', '09-28', '10-03', '10-05', '10-09', '12-25'],
 2027: ['01-01', '02-06', '02-07', '02-08', '02-09', '03-01', '05-05', '05-13', '06-06', '08-15', '08-16', '09-14', '09-15', '09-16', '10-03', '10-04', '10-09', '10-11', '12-25', '12-27'],
};
export const isHoliday = ymd => !!H[String(ymd).slice(0, 4)]?.includes(String(ymd).slice(5, 10));
// 'sun'(일요일·공휴일) | 'sat' | ''
export const dayTone = ymd => { const d = new Date(`${ymd}T12:00:00`).getDay(); return d === 0 || isHoliday(ymd) ? 'sun' : d === 6 ? 'sat' : ''; };
